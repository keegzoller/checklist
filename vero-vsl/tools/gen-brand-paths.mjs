/**
 * Pulls the handful of brand glyph paths we use out of `simple-icons` into a
 * small generated module, so the Remotion bundle does not carry the whole
 * 3,000-icon package. Re-run with `npm run icons` after changing WANT.
 *
 * Brands simple-icons does not carry (Toast, Clover, Lightspeed, NCR, Revel,
 * Google Business Profile, Simpli.fi, Klaviyo) are drawn by hand in Logos.tsx.
 */
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

const WANT = [
  'square', 'shopify', 'meta', 'googleads', 'tiktok',
  'googleanalytics', 'yelp', 'snapchat', 'nextdoor', 'google',
];

const entries = WANT.map((slug) => {
  const icon = si['si' + slug[0].toUpperCase() + slug.slice(1)];
  if (!icon) throw new Error(`simple-icons has no icon for "${slug}"`);
  return [slug, { title: icon.title, hex: '#' + icon.hex, path: icon.path }];
});

writeFileSync(
  new URL('../src/fast/brandPaths.generated.ts', import.meta.url),
  `// GENERATED by tools/gen-brand-paths.mjs -- do not edit by hand.\n` +
    `// Source: simple-icons (CC0-1.0). Each path is a 24x24 viewBox glyph.\n\n` +
    `export const BRAND_PATHS = ${JSON.stringify(Object.fromEntries(entries), null, 2)} as const;\n`
);
console.log(`wrote ${entries.length} brand paths`);
